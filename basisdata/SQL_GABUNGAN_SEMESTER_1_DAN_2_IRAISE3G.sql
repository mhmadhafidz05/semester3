-- 5. PERIKSA HASIL (KRS TIDAK PUNYA KOLOM SEMESTER)
-- Pengelompokan ini memakai kode MK khusus dari KHS Semester 1 dan 2.
WITH DATA_NILAI AS (
    SELECT CASE
             WHEN K.MTH_KODE IN (
                 'PIF251101','UIN252006','PIF251102','UIN252008',
                 'PIF251103','UIN252001','PIF251104','PIF251105'
             ) THEN 1
             WHEN K.MTH_KODE IN (
                 'PIF251206','UIN252012','UIN252007','PIF251207',
                 'PIF251208','PIF251209','PIF251210'
             ) THEN 2
           END AS SEMESTER,
           M.SKS,
           CASE TRIM(K.NILAI)
             WHEN 'A'  THEN 4.0
             WHEN 'A-' THEN 3.7
             WHEN 'B+' THEN 3.3
             WHEN 'B-' THEN 2.7
             WHEN 'C+' THEN 2.3
             WHEN 'C'  THEN 2.0
           END AS BOBOT
    FROM KRS K
    JOIN MATAKULIAH M ON M.KODE = K.MTH_KODE
    WHERE K.MHA_NIM = 12550112540
      AND K.TA = '2025/2026'
)
SELECT CASE WHEN GROUPING(SEMESTER) = 1 THEN 'KUMULATIF'
            ELSE 'SEMESTER ' || TO_CHAR(SEMESTER) END AS PERIODE,
       SUM(SKS) AS TOTAL_SKS,
       ROUND(SUM(SKS * BOBOT), 2) AS NILAI_MUTU,
       ROUND(SUM(SKS * BOBOT) / NULLIF(SUM(SKS), 0), 2) AS IP
FROM DATA_NILAI
WHERE SEMESTER IS NOT NULL
GROUP BY ROLLUP(SEMESTER)
ORDER BY GROUPING(SEMESTER), SEMESTER;


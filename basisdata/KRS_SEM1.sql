-- 10. CEK IP DARI KHS (TARGET: 19 SKS, 64.90, IP 3.42)
SELECT SUM(M.SKS) AS TOTAL_SKS,
       SUM(M.SKS * CASE TRIM(K.NILAI)
             WHEN 'A' THEN 4
             WHEN 'A-' THEN 3.7
             WHEN 'B-' THEN 2.7
             WHEN 'C' THEN 2
           END) AS TOTAL_NILAI_MUTU,
       ROUND(SUM(M.SKS * CASE TRIM(K.NILAI)
             WHEN 'A' THEN 4
             WHEN 'A-' THEN 3.7
             WHEN 'B-' THEN 2.7
             WHEN 'C' THEN 2
           END) / NULLIF(SUM(M.SKS), 0), 2) AS IP
FROM KRS K
JOIN MATAKULIAH M ON M.KODE = K.MTH_KODE
WHERE K.MHA_NIM = 12550112540 AND K.TA = '2025/2026';

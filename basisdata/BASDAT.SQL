SELECT EPE.EMPLOYEE ID ID PEGAWAI, EPE.FIRST NAME "NAMA PEGAWAI", DPT.DEPARTMENT NAME "NAMA DEPARTEMEN", EPE.SALARY GAJI, CTY.COUNTRY_NAME NEGARA FROM EMPLOYEES EPE, DEPARTMENTS DPT, LOCATIONS LCN, COUNTRIES CTY
WHERE
EPE.DEPARTMENT_ID = DPT.DEPARTMENT_ID 
AND DPT.LOCATION ID = LCN.LOCATION ID 
AND LCN.COUNTRY ID = CTY.COUNTRY ID;
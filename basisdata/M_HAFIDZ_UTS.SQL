-- 1. TABEL SUPPLIER
CREATE TABLE "SUPPLIER" (
    ID VARCHAR2(5) CONSTRAINT "SUPPLIER_ID_NN" NOT NULL ENABLE,
    NAMA VARCHAR2(20) CONSTRAINT "SUPPLIER_NAMA_NN" NOT NULL ENABLE,
    ALAMAT VARCHAR2(20),
    NO_TELP NUMBER(12),
    CONSTRAINT "SUPPLIER_PK" PRIMARY KEY (ID) USING INDEX ENABLE
);

-- 2. TABEL TOKO
CREATE TABLE "TOKO" (
    ID VARCHAR2(5) CONSTRAINT "TOKO_ID_NN" NOT NULL ENABLE,
    ALAMAT VARCHAR2(20) CONSTRAINT "TOKO_ALAMAT_NN" NOT NULL ENABLE,
    NAMA VARCHAR2(20) CONSTRAINT "TOKO_NAMA_NN" NOT NULL ENABLE,
    NO_TELP NUMBER(12) CONSTRAINT "TOKO_TELP_NN" NOT NULL ENABLE,
    CONSTRAINT "TOKO_PK" PRIMARY KEY (ID) USING INDEX ENABLE
);

-- 3. TABEL PEMBAYARAN
CREATE TABLE "PEMBAYARAN" (
    ID VARCHAR2(5) CONSTRAINT "PEMBAYARAN_ID_NN" NOT NULL ENABLE,
    JENIS_PEMBAYARAN VARCHAR2(10) CONSTRAINT "PEMBAYARAN_JENIS_NN" NOT NULL ENABLE,
    NOMINAL_PEMBAYARAN VARCHAR2(20) CONSTRAINT "PEMBAYARAN_NOMINAL_NN" NOT NULL ENABLE,
    CONSTRAINT "PEMBAYARAN_PK" PRIMARY KEY (ID) USING INDEX ENABLE
);

-- 4. TABEL BARANG
CREATE TABLE "BARANG" (
    KODE VARCHAR2(5) CONSTRAINT "BARANG_KODE_NN" NOT NULL ENABLE,
    NAMA VARCHAR2(20) CONSTRAINT "BARANG_NAMA_NN" NOT NULL ENABLE,
    HARGA_SATUAN VARCHAR2(20) CONSTRAINT "BARANG_HARGA_NN" NOT NULL ENABLE,
    CONSTRAINT "BARANG_PK" PRIMARY KEY (KODE) USING INDEX ENABLE
);

-- 5. TABEL FAKTUR
CREATE TABLE "FAKTUR" (
    NO_TRANSAKSI NUMBER(1) CONSTRAINT "FAKTUR_NO_NN" NOT NULL ENABLE,
    TGL_TRANSAKSI DATE CONSTRAINT "FAKTUR_TGL_NN" NOT NULL ENABLE,
    SUPPLIER_ID VARCHAR2(5) CONSTRAINT "FAKTUR_SUPPLIER_NN" NOT NULL ENABLE,
    TOKO_ID VARCHAR2(5) CONSTRAINT "FAKTUR_TOKO_NN" NOT NULL ENABLE,
    PEMBAYARAN_ID VARCHAR2(5) CONSTRAINT "FAKTUR_PEMBAYARAN_NN" NOT NULL ENABLE,
    CONSTRAINT "FAKTUR_PK" PRIMARY KEY (NO_TRANSAKSI) USING INDEX ENABLE
);

-- Foreign key milik FAKTUR
ALTER TABLE "FAKTUR" ADD CONSTRAINT "FAKTUR_SUPPLIER_FK"
    FOREIGN KEY (SUPPLIER_ID) REFERENCES "SUPPLIER" (ID);
ALTER TABLE "FAKTUR" ADD CONSTRAINT "FAKTUR_TOKO_FK"
    FOREIGN KEY (TOKO_ID) REFERENCES "TOKO" (ID);
ALTER TABLE "FAKTUR" ADD CONSTRAINT "FAKTUR_PEMBAYARAN_FK"
    FOREIGN KEY (PEMBAYARAN_ID) REFERENCES "PEMBAYARAN" (ID);

-- 6. TABEL DETAIL_FAKTUR
CREATE TABLE "DETAIL_FAKTUR" (
    TOTAL_HARGA VARCHAR2(20) CONSTRAINT "DETAIL_TOTAL_NN" NOT NULL ENABLE,
    QUANTITY VARCHAR2(10) CONSTRAINT "DETAIL_QTY_NN" NOT NULL ENABLE,
    DISKON VARCHAR2(20) CONSTRAINT "DETAIL_DISKON_NN" NOT NULL ENABLE,
    BARANG_KODE VARCHAR2(5) CONSTRAINT "DETAIL_BARANG_NN" NOT NULL ENABLE,
    FAKTUR_NO_TRANSAKSI NUMBER(1) CONSTRAINT "DETAIL_FAKTUR_NO_NN" NOT NULL ENABLE,
    CONSTRAINT "DETAIL_FAKTUR_PK" PRIMARY KEY (BARANG_KODE, FAKTUR_NO_TRANSAKSI) USING INDEX ENABLE
);

-- Foreign key milik DETAIL_FAKTUR
ALTER TABLE "DETAIL_FAKTUR" ADD CONSTRAINT "DETAIL_FAKTUR_BARANG_FK"
    FOREIGN KEY (BARANG_KODE) REFERENCES "BARANG" (KODE);
ALTER TABLE "DETAIL_FAKTUR" ADD CONSTRAINT "DETAIL_FAKTUR_FAKTUR_FK"
    FOREIGN KEY (FAKTUR_NO_TRANSAKSI) REFERENCES "FAKTUR" (NO_TRANSAKSI);